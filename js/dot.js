  /* 칸 하나를 통째로 그림으로 — cozy 의 swap 을 그대로 부른다(window.CCIcon).
     cozy 표에 없는 이름이면 그 함수가 아무 것도 안 하고 돌아오므로, svg 가 생겼는지로 안다. */
