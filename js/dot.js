  /* SVG 조각을 캔버스 경로로. 게임이 쓰는 것은 path·circle·ellipse·rect 뿐이다. */
  function toPath(el) {
    const n = el.tagName.toLowerCase();
    const num = a => parseFloat(el.getAttribute(a) || '0');
    const p = new Path2D();
    if (n === 'path') { const d = el.getAttribute('d'); return d ? new Path2D(d) : null; }
    if (n === 'circle') { p.arc(num('cx'), num('cy'), num('r'), 0, 6.2832); return p; }
    if (n === 'ellipse') { p.ellipse(num('cx'), num('cy'), num('rx'), num('ry'), 0, 0, 6.2832); return p; }
    if (n === 'rect') { p.rect(num('x'), num('y'), num('width'), num('height')); return p; }
    return null;
  }
